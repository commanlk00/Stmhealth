export function searchHazardousBusinesses(query: string): Array<HazardousBusinessTypeItem & { groupName: string; groupId: string; groupNo: number }> {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const results: Array<HazardousBusinessTypeItem & { groupName: string; groupId: string; groupNo: number }> = [];

  for (const group of HAZARDOUS_BUSINESS_GROUPS) {
    for (const item of group.types) {
      if (
        item.name.toLowerCase().includes(q) ||
        item.shortName.toLowerCase().includes(q) ||
        item.code.toLowerCase().includes(q) ||
        (item.subCategory && item.subCategory.toLowerCase().includes(q)) ||
        group.name.toLowerCase().includes(q) ||
        group.shortName.toLowerCase().includes(q) ||
        item.keySanitationRequirements.some((r) => r.toLowerCase().includes(q))
      ) {
        results.push({
          ...item,
          groupId: group.id,
          groupNo: group.groupNo,
          groupName: group.name,
        });
      }
    }
  }

  return results;
}

// Helper: Find item by code
export function findHazardousTypeByCode(code: string): { group: HazardousBusinessGroup; item: HazardousBusinessTypeItem } | null {
  for (const group of HAZARDOUS_BUSINESS_GROUPS) {
    const item = group.types.find((t) => t.code === code);
    if (item) {
      return { group, item };
    }
  }
  return null;
}
